-- Esquema inicial de AdaptCode UTP.
--
-- Esta migracion representa el estado del esquema ANTES de las iteraciones de
-- integridad (V2), tokens de refresco (V3) y pausa/limites (V4). Se mantiene
-- idempotente (IF NOT EXISTS) porque algunas bases ya tenian el esquema creado
-- por Hibernate antes de adoptar Flyway; esas bases se marcan con
-- baseline-version=1 y solo reciben V2 en adelante. Una base vacia ejecuta
-- V1 -> V2 -> V3 -> V4 sin intervencion manual.

CREATE TABLE IF NOT EXISTS usuarios (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	correo VARCHAR(254) NOT NULL UNIQUE,
	contrasena_hash VARCHAR(255) NOT NULL,
	nombres VARCHAR(100) NOT NULL,
	apellidos VARCHAR(100) NOT NULL,
	rol VARCHAR(32) NOT NULL,
	activo BOOLEAN NOT NULL,
	genero VARCHAR(16),
	fecha_nacimiento DATE,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	credencial_cambiada_en TIMESTAMP WITH TIME ZONE,
	CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ESTUDIANTE_UTP', 'DOCENTE_UTP', 'USUARIO_EXTERNO')),
	CONSTRAINT ck_usuarios_genero CHECK (genero IN ('MASCULINO', 'FEMENINO'))
);

CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios (rol);

CREATE TABLE IF NOT EXISTS cursos (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(120) NOT NULL UNIQUE,
	activo BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS temas (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	curso_id BIGINT NOT NULL REFERENCES cursos (id) ON DELETE CASCADE,
	nombre VARCHAR(120) NOT NULL,
	activo BOOLEAN NOT NULL,
	CONSTRAINT uk_temas_curso_nombre UNIQUE (curso_id, nombre)
);

CREATE TABLE IF NOT EXISTS micro_retos (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	tema_id BIGINT NOT NULL REFERENCES temas (id) ON DELETE CASCADE,
	codigo VARCHAR(40) NOT NULL UNIQUE,
	tipo VARCHAR(32) NOT NULL,
	nivel VARCHAR(16) NOT NULL,
	enunciado VARCHAR(1000) NOT NULL,
	codigo_base VARCHAR(4000),
	lenguaje VARCHAR(32),
	activo BOOLEAN NOT NULL,
	CONSTRAINT ck_micro_retos_tipo CHECK (tipo IN ('SELECCION_MULTIPLE', 'ORDENAR_BLOQUES', 'PREDECIR_SALIDA', 'SELECCIONAR_FRAGMENTO')),
	CONSTRAINT ck_micro_retos_nivel CHECK (nivel IN ('BASICO', 'INTERMEDIO', 'AVANZADO'))
);

CREATE TABLE IF NOT EXISTS alternativas_micro_reto (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	micro_reto_id BIGINT NOT NULL REFERENCES micro_retos (id) ON DELETE CASCADE,
	texto VARCHAR(1000),
	codigo VARCHAR(4000),
	lenguaje VARCHAR(32),
	correcta BOOLEAN NOT NULL,
	orden_visual INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS bloques_micro_reto (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	micro_reto_id BIGINT NOT NULL REFERENCES micro_retos (id) ON DELETE CASCADE,
	texto VARCHAR(1000) NOT NULL,
	orden_correcto INTEGER NOT NULL,
	orden_visual INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS retroalimentaciones (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	micro_reto_id BIGINT NOT NULL REFERENCES micro_retos (id) ON DELETE CASCADE,
	alternativa_id BIGINT REFERENCES alternativas_micro_reto (id) ON DELETE CASCADE,
	causa VARCHAR(500) NOT NULL,
	sugerencia VARCHAR(500) NOT NULL,
	explicacion VARCHAR(1500) NOT NULL,
	secuencia_textual VARCHAR(1500) NOT NULL
);

CREATE TABLE IF NOT EXISTS preguntas_docente (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	docente_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	tema_id BIGINT NOT NULL REFERENCES temas (id) ON DELETE CASCADE,
	micro_reto_origen_id BIGINT REFERENCES micro_retos (id),
	tipo VARCHAR(32) NOT NULL,
	nivel VARCHAR(16) NOT NULL,
	origen VARCHAR(16) NOT NULL,
	enunciado VARCHAR(1000) NOT NULL,
	activa BOOLEAN NOT NULL,
	CONSTRAINT ck_preguntas_docente_tipo CHECK (tipo IN ('SELECCION_MULTIPLE', 'ORDENAR_BLOQUES', 'PREDECIR_SALIDA', 'SELECCIONAR_FRAGMENTO')),
	CONSTRAINT ck_preguntas_docente_nivel CHECK (nivel IN ('BASICO', 'INTERMEDIO', 'AVANZADO')),
	CONSTRAINT ck_preguntas_docente_origen CHECK (origen IN ('INSTITUCIONAL', 'COPIA', 'PROPIA'))
);

CREATE INDEX IF NOT EXISTS idx_preguntas_docente_docente ON preguntas_docente (docente_id);

CREATE TABLE IF NOT EXISTS alternativas_docente (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	pregunta_id BIGINT NOT NULL REFERENCES preguntas_docente (id) ON DELETE CASCADE,
	texto VARCHAR(1000),
	codigo VARCHAR(4000),
	lenguaje VARCHAR(32),
	correcta BOOLEAN NOT NULL,
	orden_visual INTEGER NOT NULL,
	CONSTRAINT uk_alternativas_docente_pregunta_orden UNIQUE (pregunta_id, orden_visual)
);

CREATE TABLE IF NOT EXISTS retroalimentaciones_docente (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	pregunta_id BIGINT NOT NULL REFERENCES preguntas_docente (id) ON DELETE CASCADE,
	alternativa_id BIGINT NOT NULL REFERENCES alternativas_docente (id) ON DELETE CASCADE,
	causa VARCHAR(500) NOT NULL,
	sugerencia VARCHAR(500) NOT NULL,
	explicacion VARCHAR(1500) NOT NULL,
	secuencia_textual VARCHAR(1500) NOT NULL,
	CONSTRAINT uk_retro_docente_alternativa UNIQUE (alternativa_id)
);

CREATE TABLE IF NOT EXISTS quizzes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	docente_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	titulo VARCHAR(120) NOT NULL,
	estado VARCHAR(16) NOT NULL,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT ck_quizzes_estado CHECK (estado IN ('BORRADOR', 'LISTO'))
);

CREATE INDEX IF NOT EXISTS idx_quizzes_docente ON quizzes (docente_id);

CREATE TABLE IF NOT EXISTS quiz_items (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	quiz_id BIGINT NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
	pregunta_id BIGINT NOT NULL REFERENCES preguntas_docente (id) ON DELETE CASCADE,
	orden INTEGER NOT NULL,
	CONSTRAINT uk_quiz_items_quiz_orden UNIQUE (quiz_id, orden),
	CONSTRAINT uk_quiz_items_quiz_pregunta UNIQUE (quiz_id, pregunta_id)
);

CREATE TABLE IF NOT EXISTS salas (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	docente_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	quiz_origen_id BIGINT NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
	quiz_version_congelada_en TIMESTAMP WITH TIME ZONE,
	pin VARCHAR(6) NOT NULL UNIQUE,
	estado VARCHAR(16) NOT NULL,
	tiempo_por_pregunta INTEGER NOT NULL,
	ampliacion VARCHAR(16) NOT NULL,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT ck_salas_estado CHECK (estado IN ('BORRADOR', 'SALA_ESPERA', 'EN_CURSO', 'PAUSADA', 'FINALIZADA')),
	CONSTRAINT ck_salas_ampliacion CHECK (ampliacion IN ('ESTANDAR', 'MAS_50', 'MAS_100'))
);

CREATE INDEX IF NOT EXISTS idx_salas_docente ON salas (docente_id);

CREATE TABLE IF NOT EXISTS participaciones_sala (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	sala_id BIGINT NOT NULL REFERENCES salas (id) ON DELETE CASCADE,
	estudiante_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	expulsado BOOLEAN NOT NULL,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT uk_participaciones_sala_estudiante UNIQUE (sala_id, estudiante_id)
);

CREATE TABLE IF NOT EXISTS respuestas_sala (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	participacion_id BIGINT NOT NULL REFERENCES participaciones_sala (id) ON DELETE CASCADE,
	pregunta_id BIGINT NOT NULL REFERENCES preguntas_docente (id) ON DELETE CASCADE,
	acierto BOOLEAN NOT NULL,
	omitida BOOLEAN NOT NULL,
	tiempo_ms BIGINT,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT uk_respuestas_participacion_pregunta UNIQUE (participacion_id, pregunta_id)
);

CREATE TABLE IF NOT EXISTS anulaciones_pregunta (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	sala_id BIGINT NOT NULL REFERENCES salas (id) ON DELETE CASCADE,
	pregunta_id BIGINT NOT NULL REFERENCES preguntas_docente (id) ON DELETE CASCADE,
	docente_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	motivo VARCHAR(500) NOT NULL,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS codigos_verificacion (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	correo VARCHAR(254) NOT NULL,
	codigo VARCHAR(64) NOT NULL,
	tipo VARCHAR(32) NOT NULL,
	expira_en TIMESTAMP WITH TIME ZONE NOT NULL,
	usado BOOLEAN NOT NULL,
	intentos INTEGER,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT ck_codigos_verificacion_tipo CHECK (tipo IN ('VERIFICACION_CUENTA', 'RECUPERACION'))
);

CREATE INDEX IF NOT EXISTS idx_codigos_correo ON codigos_verificacion (correo);

CREATE TABLE IF NOT EXISTS insignias_obtenidas (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	tipo VARCHAR(32) NOT NULL,
	obtenido_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT uk_insignias_usuario_tipo UNIQUE (usuario_id, tipo),
	CONSTRAINT ck_insignias_obtenidas_tipo CHECK (tipo IN ('PRIMER_PASO', 'EXPLORADOR', 'DOMINIO_BASICO', 'PERSEVERANTE', 'CURSO_COMPLETADO'))
);

CREATE TABLE IF NOT EXISTS intentos (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	micro_reto_id BIGINT NOT NULL REFERENCES micro_retos (id),
	nro_intento INTEGER NOT NULL,
	acierto BOOLEAN NOT NULL,
	uso_ayuda BOOLEAN NOT NULL,
	tiempo_ms BIGINT,
	creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT uk_intentos_usuario_reto_nro UNIQUE (usuario_id, micro_reto_id, nro_intento)
);

CREATE INDEX IF NOT EXISTS idx_intentos_usuario_reto ON intentos (usuario_id, micro_reto_id);

CREATE TABLE IF NOT EXISTS progreso_micro_retos (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
	micro_reto_id BIGINT NOT NULL REFERENCES micro_retos (id),
	completado BOOLEAN NOT NULL,
	resuelto_con_ayuda BOOLEAN NOT NULL,
	punto_dominio BOOLEAN NOT NULL,
	actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT uk_progreso_usuario_reto UNIQUE (usuario_id, micro_reto_id)
);

CREATE TABLE IF NOT EXISTS preferencias_accesibilidad (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios (id) ON DELETE CASCADE,
	tamano_texto VARCHAR(32) NOT NULL,
	tema VARCHAR(32) NOT NULL,
	modo_daltonismo BOOLEAN NOT NULL,
	reduccion_movimiento BOOLEAN NOT NULL,
	sonido_activado BOOLEAN NOT NULL
);
